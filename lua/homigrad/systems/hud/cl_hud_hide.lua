	["CHudSuitPower"] = true,
}

hook.Add("HUDShouldDraw", "homigrad", function(name)
	if hide[name] then return false end
	if lply and lply.PlayerClassName == "Gordon" and gordon_hide[name] then
		return false
	end
end)

